-- Validação também no servidor: não depende da interface.
CREATE FUNCTION public.web_validate_build() RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER SET search_path='' AS $$
DECLARE cpu public.processador; board public.placa_mae; ram public.memoria; gpu public.placa_video; psu public.fonte;
BEGIN
 SELECT * INTO STRICT cpu FROM public.processador WHERE id=NEW.processador_id;
 SELECT * INTO STRICT board FROM public.placa_mae WHERE id=NEW.placa_mae_id;
 SELECT * INTO STRICT ram FROM public.memoria WHERE id=NEW.memoria_id;
 SELECT * INTO STRICT gpu FROM public.placa_video WHERE id=NEW.placa_video_id;
 SELECT * INTO STRICT psu FROM public.fonte WHERE id=NEW.fonte_id;
 IF lower(cpu.socket)<>lower(board.socket) THEN RAISE EXCEPTION 'Socket incompatível'; END IF;
 IF lower(ram.tipo)<>lower(board.tipo_memoria) THEN RAISE EXCEPTION 'Memória incompatível'; END IF;
 IF psu.potencia<ceil((cpu.consumo+board.consumo+gpu.consumo+10)*1.2) THEN RAISE EXCEPTION 'Fonte insuficiente'; END IF;
 RETURN NEW;
END; $$;
REVOKE ALL ON FUNCTION public.web_validate_build() FROM PUBLIC, anon, authenticated;
CREATE TRIGGER web_build_validation BEFORE INSERT OR UPDATE ON public.web_build FOR EACH ROW EXECUTE FUNCTION public.web_validate_build();
-- Tabelas legadas com senhas e builds desktop permanecem inacessíveis pela API.
REVOKE ALL ON public.usuario, public.build, public.componente_importado FROM anon, authenticated;
COMMIT;
